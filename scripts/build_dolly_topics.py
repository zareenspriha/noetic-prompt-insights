def bucket(text, salt):
    return int(hashlib.sha256((salt + text.lower()).encode()).hexdigest(), 16) % 1000 / 1000


def main():
    if not RAW.exists():
        RAW.parent.mkdir(parents=True, exist_ok=True)
        urllib.request.urlretrieve(URL, RAW)
    if hashlib.sha256(RAW.read_bytes()).hexdigest() != SHA256:
        sys.exit(f"{RAW} does not match the pinned Dolly-15k checksum")
    source = RAW.read_text().splitlines()
    rows, seen = [], set()
    for topic, lines in LABELS.items():
        for line in sorted(set(lines)):
            text = " ".join(json.loads(source[line])["instruction"].split())
            if text.lower() in seen:
                continue  # exact duplicates would leak between train and test
            seen.add(text.lower())
            rows.append(
                dict(
                    id=f"dolly-{line}",
                    text=text,
                    topic=topic,
                    split="test" if bucket(text, "split") < TEST_SHARE else "train",
                    # Folds let the k-NN cutoff be tuned inside the training rows only.
                    template_family=f"dolly-fold-{int(bucket(text, 'fold') * 3)}",
                    source="databricks-dolly-15k (CC BY-SA 3.0), topic label ours",
                )
            )
    OUT.write_text("".join(json.dumps(row) + "\n" for row in rows))
    print(f"Wrote {len(rows)} labelled rows to {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
